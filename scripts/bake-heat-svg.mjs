/**
 * @built F-48 the static heat map: an SVG built offline from the committed ACS table
 *
 * R10.1/R10.13: when tiles fail, the lens still shows a map. This script writes one
 * from data already in the repository — `public/data/ma-tracts.topo.json` for the
 * shapes and `public/data/ma-tract-stats.json` for the oil share — so the fallback
 * costs the runtime nothing: no network, no key, no dependency.
 *
 *   node scripts/bake-heat-svg.mjs            # write public/data/ma-heat-map.svg
 *   node scripts/bake-heat-svg.mjs --check    # report size, write nothing
 *
 * The colour breaks and the 750 gal assumption mirror `lib/map/heat.ts` and
 * `components/map/palette.ts`; both are named here so a change has one address.
 */

import { readFileSync, statSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { feature } from 'topojson-client'

const TRACTS = 'public/data/ma-tracts.topo.json'
const STATS = 'public/data/ma-tract-stats.json'
const OUT = 'public/data/ma-heat-map.svg'

// components/map/palette.ts HEAT_RAMP, as literals (MapLibre's parser cannot read oklch).
const RAMP = ['#f7efda', '#f0d5ac', '#e8ab70', '#d3793c', '#ac451c']
const NO_DATA = '#d9d6cf'
// lib/map/heat.ts BREAKS.oil_share — the metric a static image can honestly show,
// because it is the one that does not change with the year.
const BREAKS = [0.05, 0.15, 0.3, 0.5]
const LABELS = ['Under 5%', '5 to 15%', '15 to 30%', '30 to 50%', '50% or more']
const GAL_PER_HOUSEHOLD = 750
const WIDTH = 960
const HEIGHT = 600
const PAD = 24

const checkOnly = process.argv.includes('--check')

const topo = JSON.parse(readFileSync(resolve(process.cwd(), TRACTS), 'utf8'))
const stats = JSON.parse(readFileSync(resolve(process.cwd(), STATS), 'utf8'))
const collection = feature(topo, topo.objects.tracts)

const oilShareOf = (geoid) => {
  const values = stats.tracts[geoid]
  if (!Array.isArray(values)) return null
  const households = values[1]
  const oil = values[2]
  return households > 0 ? oil / households : null
}

const colourOf = (share) => {
  if (share === null) return NO_DATA
  let i = 0
  while (i < BREAKS.length && share >= BREAKS[i]) i += 1
  return RAMP[i]
}

// -- project ----------------------------------------------------------------
let minLon = Infinity
let maxLon = -Infinity
let minLat = Infinity
let maxLat = -Infinity
const ringsOf = (geometry) =>
  geometry.type === 'Polygon' ? geometry.coordinates : geometry.coordinates.flat()

for (const f of collection.features) {
  for (const ring of ringsOf(f.geometry)) {
    for (const [lon, lat] of ring) {
      if (lon < minLon) minLon = lon
      if (lon > maxLon) maxLon = lon
      if (lat < minLat) minLat = lat
      if (lat > maxLat) maxLat = lat
    }
  }
}

const latMid = ((minLat + maxLat) / 2) * (Math.PI / 180)
const cos = Math.cos(latMid)
const spanX = (maxLon - minLon) * cos
const spanY = maxLat - minLat
const scale = Math.min((WIDTH - PAD * 2) / spanX, (HEIGHT - PAD * 2) / spanY)
const offsetX = (WIDTH - spanX * scale) / 2
const offsetY = (HEIGHT - spanY * scale) / 2

const round1 = (n) => Math.round(n * 10) / 10
const project = (lon, lat) => [round1(offsetX + (lon - minLon) * cos * scale), round1(offsetY + (maxLat - lat) * scale)]

const pathOf = (geometry) =>
  ringsOf(geometry)
    .map((ring) => {
      const points = ring.map(([lon, lat]) => project(lon, lat))
      if (points.length < 3) return ''
      return `M${points.map(([x, y]) => `${x} ${y}`).join('L')}Z`
    })
    .join('')

// -- totals -----------------------------------------------------------------
let households = 0
let oilHouseholds = 0
let tracts = 0
for (const [geoid, values] of Object.entries(stats.tracts)) {
  const share = oilShareOf(geoid)
  if (share === null) continue
  tracts += 1
  households += values[1]
  oilHouseholds += values[2]
}
const stateShare = households > 0 ? oilHouseholds / households : 0
const pct = (share) => `${(Math.round(share * 1000) / 10).toLocaleString('en-US')}%`

const paths = collection.features
  .map((f) => {
    const geoid = String(f.properties?.geoid ?? '')
    const share = oilShareOf(geoid)
    const d = pathOf(f.geometry)
    if (!d) return ''
    return `<path d="${d}" fill="${colourOf(share)}"><title>Tract ${geoid} · ${share === null ? 'no estimate' : `${pct(share)} oil-heated`}</title></path>`
  })
  .join('')

const legend = RAMP.map(
  (colour, i) =>
    `<g transform="translate(0 ${i * 18})"><rect width="22" height="11" rx="2" fill="${colour}" stroke="#c9c3b8"/><text x="30" y="10" font-size="11" fill="#4a443c">${LABELS[i]}</text></g>`,
).join('')

const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!--
  @built F-48 static Heat lens, generated by scripts/bake-heat-svg.mjs — do not edit by hand.
  Shapes: US Census TIGERweb tracts (STATE=25), committed as ${TRACTS}.
  Values: ACS B25040 via Census Reporter, fetched ${stats._meta.fetchedAt}.
  ${tracts} tracts with an estimate. Oil spend elsewhere on /map is ${GAL_PER_HOUSEHOLD} gal/household × the DOER oil price.
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" width="${WIDTH}" height="${HEIGHT}" role="img" aria-labelledby="heat-static-title heat-static-desc">
  <title id="heat-static-title">Massachusetts heating oil by census tract</title>
  <desc id="heat-static-desc">Share of occupied homes heating with oil in ${tracts} census tracts. Statewide ${pct(stateShare)} of ${households.toLocaleString('en-US')} homes; ${oilHouseholds.toLocaleString('en-US')} heat with oil. A static fallback for the interactive map; the table view carries the same numbers as text.</desc>
  <rect width="${WIDTH}" height="${HEIGHT}" fill="#f4f1ea"/>
  <g stroke="#f4f1ea" stroke-width="0.35" fill-rule="evenodd">${paths}</g>
  <g transform="translate(${WIDTH - 210} ${HEIGHT - 150})">
    <rect width="190" height="130" rx="6" fill="#fffdf9" stroke="#d8d2c6"/>
    <text x="12" y="20" font-size="12" font-family="system-ui, sans-serif" fill="#26221c">Share of homes on oil</text>
    <g transform="translate(12 32)" font-family="system-ui, sans-serif">${legend}</g>
  </g>
  <text x="${PAD}" y="${HEIGHT - 12}" font-size="12" font-family="system-ui, sans-serif" fill="#26221c">Massachusetts · ${pct(stateShare)} of ${households.toLocaleString('en-US')} occupied homes heat with oil · ACS B25040</text>
</svg>
`

if (checkOnly) {
  for (const rel of [OUT, 'public/data/ma-heat-map.png']) {
    const bytes = statSync(resolve(process.cwd(), rel)).size
    console.log(`${rel} — ${(bytes / 1024).toFixed(0)} KB`)
  }
  process.exit(0)
}

writeFileSync(resolve(process.cwd(), OUT), svg)
console.log(`${OUT} — ${(Buffer.byteLength(svg) / 1024).toFixed(0)} KB, ${collection.features.length} tract paths`)

// R10.1 names a PNG. The SVG above is the source of truth; rasterise it when
// sharp is present (Next ships it as an optional dependency). The committed PNG
// is what the fallback renders, so a machine without sharp still has the image;
// it just cannot regenerate it.
try {
  const { default: sharp } = await import('sharp')
  const png = resolve(process.cwd(), 'public/data/ma-heat-map.png')
  await sharp(Buffer.from(svg)).png({ compressionLevel: 9, palette: true }).toFile(png)
  console.log(`${'public/data/ma-heat-map.png'} — ${(statSync(png).size / 1024).toFixed(0)} KB`)
} catch (error) {
  console.warn(
    `public/data/ma-heat-map.png not regenerated (${error instanceof Error ? error.message : String(error)}).`,
    'The committed PNG is unchanged; install sharp to rebuild it.',
  )
}
